export type FrequencyLevel = 'high' | 'medium' | 'low';
export type MapLayerType = 'china' | 'world' | 'both';

// ===== 核心数据结构 =====

export interface DataTable {
  headers: string[];
  rows: string[][];
}

export interface KnowledgePoint {
  id: string;
  name: string;
  frequency: FrequencyLevel;
  isLiaoningFeature?: boolean;
  concept: string;           // 是什么（必背定义/核心概念）
  data?: DataTable;          // 关键数据/公式/图表
  causality?: string;        // 为什么（核心因果链）
  examPatterns: string;     // 怎么考（高频题型+得分关键词）
  traps: string[];          // 易错提醒（辽宁卷常见陷阱）
  terms: string[];          // 地理术语
  mapVisualization?: {
    type: MapLayerType;
    highlight?: string[];
    markers?: { name: string; coord: [number, number]; description?: string }[];
    layers?: string[];
  };
  additionalNotes?: string;  // 补充说明
}

export interface Topic {
  id: string;
  name: string;
  frequency: FrequencyLevel;
  isLiaoningFeature?: boolean;
  description?: string;
  points: KnowledgePoint[];
  template?: string;        // 关联答题模板ID
  terms: string[];          // 专题术语黑话
  mapLayers?: string[];     // 关联地图图层
}

export interface Module {
  id: string;
  name: string;
  score: string;
  textbook: string;         // 对应教材
  description: string;
  topics: Topic[];
  terms: string[];          // 模块通用术语
  mapLayers?: string[];     // 关联地图图层
}

export interface AnswerTemplate {
  id: string;
  name: string;
  category: string;
  description: string;
  structure: string;        // 模板结构
  applicationSteps: string[];
  examples: {
    question: string;
    answer: string;
    points: string[];
  }[];
  examTips: string[];
}

export interface GlossaryCategory {
  id: string;
  name: string;
  terms: {
    term: string;
    description: string;
    usage?: string;
  }[];
}

export interface LiaoningFeature {
  id: string;
  name: string;
  category: 'natural' | 'human' | 'ecology' | 'energy';
  description: string;
  relatedTopics: string[];
  keyPoints: string[];
}

