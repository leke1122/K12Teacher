export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { unitIds = ['u1', 'u2', 'u3', 'u4', 'u5'] } = body;

    if (!isSupabaseConfigured || !supabase) {
      return NextResponse.json({
        success: false,
        message: 'Supabase未配置，无法导入数据'
      }, { status: 500 });
    }

    const results = [];

    for (const unitId of unitIds) {
      let unitData;

      if (unitId === 'u1') {
        unitData = UNIT1_DATA;
      } else if (unitId === 'u2') {
        unitData = UNIT2_DATA;
      } else if (unitId === 'u3') {
        unitData = UNIT3_DATA;
      } else if (unitId === 'u4') {
        unitData = UNIT4_DATA;
      } else if (unitId === 'u5') {
        unitData = UNIT5_DATA;
      } else {
        continue;
      }

      // 构建导入记录
      const importRecord = {
        id: `${USER_ID}-${unitId}`,
        user_id: USER_ID,
        file_name: `${unitData.unitTitle}.json`,
        unit_id: unitId,
        textbook_id: unitData.textbookId,
        unit_title: unitData.unitTitle,
        data: unitData,
        concepts_count: unitData.concepts.length,
        events_count: unitData.events.length,
        links_count: unitData.causalLinks?.length || 0,
        exam_focus_count: unitData.examFocus?.length || 0,
        imported_at: new Date().toISOString(),
      };

      // 先删除旧记录
      await supabase
        .from('docx_imports')
        .delete()
        .eq('user_id', USER_ID)
        .eq('unit_id', unitId);

      // 插入新记录
      const { data, error } = await supabase
        .from('docx_imports')
        .upsert(importRecord, {
          onConflict: 'id',
        })
        .select()
        .single();

      if (error) {
        console.error(`导入单元 ${unitId} 失败:`, error);
        results.push({
          unitId,
          success: false,
          error: error.message
        });
      } else {
        console.log(`导入单元 ${unitId} 成功`);
        results.push({
          unitId,
          success: true,
          data: {
            conceptsCount: unitData.concepts.length,
            eventsCount: unitData.events.length,
            linksCount: unitData.causalLinks?.length || 0,
            examFocusCount: unitData.examFocus?.length || 0,
            memoryFormulasCount: unitData.memoryFormulas?.length || 0
          }
        });
      }
    }

    return NextResponse.json({
      success: true,
      message: '数据导入完成',
      results
    });

  } catch (error) {
    console.error('导入历史单元数据失败:', error);
    return NextResponse.json({
      success: false,
      message: '导入失败',
      error: error instanceof Error ? error.message : '未知错误'
    }, { status: 500 });
  }
}
